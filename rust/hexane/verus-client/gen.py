#!/usr/bin/env python3
"""The acceptance clients of hexane's API as a crate outside hexane.

    gen.py [OUTDIR]        (default: ../../target/verus-client)

Writes OUTDIR/{Cargo.toml, src/lib.rs, tests/run.rs}. src/lib.rs is
hexane's src/verified/client_proof.rs word for word, but for what a
crate outside hexane must say differently:

* the imports name `hexane` instead of `super` and `crate`;
* the crate has a feature `bijou64`, on by default, which asks for
  hexane's and under which the clients of that codec are compiled;
* the items are public, so that the tests can call them;
* a direct `from_iter` call is written as `collect()` (Verus panics on
  the direct call when the `FromIterator` is of another verified crate).

tests/run.rs is this directory's run.rs. See README.md for what to run
on the crate and why.
"""
import os
import re
import shutil
import sys

here = os.path.dirname(os.path.abspath(__file__))
hexane = os.path.dirname(here)
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(hexane, "..", "target", "verus-client")
out = os.path.abspath(out)
t = open(os.path.join(hexane, "src", "verified", "client_proof.rs")).read()

# `use super::{...}`: what is specification is imported for Verus only
m = re.search(r"use super::\{(.*?)\};\n", t, re.S)
names = [n.strip() for n in m.group(1).replace("\n", " ").split(",") if n.strip()]
EXEC_FNS = {"refused", "lebsize", "ulebsize"}  # lower-case names that are code, not specification
ghost = [n for n in names if n[0].islower() and n not in EXEC_FNS]
code = [n for n in names if n not in ghost]
imports = "#[cfg(verus_keep_ghost)]\nuse hexane::{%s};\nuse hexane::{%s};\n" % (
    ", ".join(ghost),
    ", ".join(code),
)
t = t[: m.start()] + imports + t[m.end() :]
assert t.count("use crate::{") == 1
t = t.replace("use crate::{", "use hexane::{")
# the modules that name a codec, and the second codec itself
for a, b in [
    ("use super::bijou;\n", "use hexane::bijou;\n"),
    ("use super::leb128;\n", "use hexane::leb128;\n"),
    ("use crate::Bijou64;\n", "use hexane::Bijou64;\n"),
]:
    assert t.count(a) == 1, a
    t = t.replace(a, b)
assert "super::" not in t and "crate::" not in t, "an import this script does not know"

# the module's documentation ends at the first empty line
doc_end = t.index("\n\n") + 1
assert all(line.startswith("//!") for line in t[:doc_end].splitlines())
t = (
    "//! The acceptance clients of hexane's API as a crate outside hexane\n"
    "//! (generated from hexane's src/verified/client_proof.rs; do not edit).\n"
    "//!\n"
    + t[:doc_end].replace("\n//! This module exists only while Verus checks the crate.\n", "\n")
    # a normal build erases the ghost code, and what only it uses is then
    # unused; nor is what `verus!` expands to written as the lints ask
    + "\n#![allow(unused_imports, unused_variables, non_shorthand_field_patterns)]\n"
    + t[doc_end:]
)

t = t.replace("#[allow(dead_code)]\n", "")
# Verus panics on a direct `from_iter` call whose `FromIterator` is of
# another verified crate (an internal error, vir/src/sst_to_air_func.rs).
# `collect()` is the same call.
t, n_from_iter = re.subn(
    r"let (\w+) = Column::<(.+)>::from_iter\((\w+)\);",
    r"let \1: Column<\2> = \3.into_iter().collect();",
    t,
)
assert "from_iter" not in t, "a from_iter call this script does not rewrite"
n_fn = len(re.findall(r"^(?:fn|proof fn|spec fn) ", t, re.M))
t = re.sub(r"^fn ", "pub fn ", t, flags=re.M)
t = re.sub(r"^proof fn ", "pub proof fn ", t, flags=re.M)
t = re.sub(r"^spec fn ", "pub open spec fn ", t, flags=re.M)
t = re.sub(r"^(enum|struct) ", r"pub \1 ", t, flags=re.M)

os.makedirs(os.path.join(out, "src"), exist_ok=True)
os.makedirs(os.path.join(out, "tests"), exist_ok=True)
open(os.path.join(out, "src", "lib.rs"), "w").write(t)
shutil.copy(os.path.join(here, "run.rs"), os.path.join(out, "tests", "run.rs"))
vstd = re.search(r'^vstd = "(.*)"$', open(os.path.join(hexane, "Cargo.toml")).read(), re.M).group(1)
open(os.path.join(out, "Cargo.toml"), "w").write(
    """# Generated by hexane's verus-client/gen.py; do not edit.
[package]
name = "verus-client"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
hexane = { path = "%s" }
vstd = "%s"

[features]
default = ["bijou64"]
bijou64 = ["hexane/bijou64"]

[package.metadata.verus]
verify = true

[lints.rust]
unexpected_cfgs = { level = "warn", check-cfg = ["cfg(verus_keep_ghost)"] }

# a workspace of its own: it is not a member of the one it may lie in
[workspace]
"""
    % (hexane, vstd)
)
# the versions hexane is built with, where a lock file says them
lock = os.path.join(hexane, "..", "Cargo.lock")
if os.path.exists(lock) and not os.path.exists(os.path.join(out, "Cargo.lock")):
    shutil.copy(lock, os.path.join(out, "Cargo.lock"))
print("%s: %d clients at the top level, %d from_iter calls written as collect(), %d lines" % (
    out, n_fn, n_from_iter, t.count("\n")))
